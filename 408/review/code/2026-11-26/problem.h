#ifndef PROBLEM_H
#define PROBLEM_H

#include <stdbool.h>
#include <stddef.h>

/*
 * 题目来源：[真题原题 · 2010年 第42题]
 *
 * 题目描述：
 *   设将 n（n > 1）个整数存放到一维数组 R[0..n-1] 中。
 *   请设计一个在时间和空间两方面都尽可能高效的算法，将 R 中保存的序列
 *   循环左移 p（0 < p < n）个位置，即将 R 中的数据由
 *   <x0, x1, ..., xn-1> 变换为 <xp, xp+1, ..., xn-1, x0, x1, ..., xp-1>。
 *
 * 结构体与接口契约说明：
 *   1. 一维数组 R 下标从 0 开始，有效元素范围为 R[0..n-1]。
 *   2. 常规输入满足 n > 1 且 0 < p < n；边界防御要求：当 R == NULL、
 *      n <= 1 或 p <= 0（或 p % n == 0）时，函数应安全返回且不发生越界访问。
 *   3. 要求在原地完成变换，追求最优的时间复杂度 O(n) 与空间复杂度 O(1)。
 */

/* 目标函数原型 */
void left_shift(int R[], int n, int p);

#endif /* PROBLEM_H */
